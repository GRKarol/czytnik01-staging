bool invertedPunctuationBaseByte(uint8_t value, uint8_t &base) {
  switch (value) {
    case 0x16:
      base = static_cast<uint8_t>('!');
      return true;
    case 0x17:
      base = static_cast<uint8_t>('?');
      return true;
    default:
      return false;
  }
}

bool shouldDrawInvertedGlyph(char c) {
  uint8_t base = 0;
  return invertedPunctuationBaseByte(LatinText::byteValue(c), base);
}

