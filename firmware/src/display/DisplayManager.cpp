ReaderGlyph serifGlyphForByte(uint8_t value) {
  // The embedded serif bitmap only covers ASCII 32-126 — unlike the
  // OpenDyslexic/AtkinsonHyperlegible cases below, this used to fall
  // straight to a literal '?' for every accented byte (Polish ą/ę/ś/ć/...
  // included), which is what showed up as a wrong/garbled character in
  // book titles and any other UI text drawn in the default typeface.
  // Transliterate to the closest plain-ASCII letter instead, same as the
  // other typefaces already do.
  if (value < kEmbeddedSerifFirstChar || value > kEmbeddedSerifLastChar) {
    value = LatinText::fallbackAsciiByte(value);
  }
  const EmbeddedSerifGlyph &glyph = kEmbeddedSerifGlyphs[value - kEmbeddedSerifFirstChar];
  return {kEmbeddedSerifBitmaps + glyph.bitmapOffset, glyph.xOffset, glyph.width, glyph.xAdvance,
          kEmbeddedSerifHeight};
}

ReaderGlyph serif70GlyphForByte(uint8_t value) {
  if (value < kEmbeddedSerif70FirstChar || value > kEmbeddedSerif70LastChar) {
    value = LatinText::fallbackAsciiByte(value);
  }
  const EmbeddedSerif70Glyph &glyph = kEmbeddedSerif70Glyphs[value - kEmbeddedSerif70FirstChar];
  return {kEmbeddedSerif70Bitmaps + glyph.bitmapOffset, glyph.xOffset, glyph.width,
          glyph.xAdvance, kEmbeddedSerif70Height};
}

// SD-generated fonts (tools/generate_embedded_font.py) carry each font's
// real space-glyph metric, which for typical Google Fonts book faces comes
// out to ~0.15-0.2x the glyph raster height. The three built-in fonts sit
// at ~0.29-0.5x (measured from their embedded glyph tables). At reading
// scale that narrower space reads as barely-there, so multi-word runs of
// dimmed context text (RSVP phantom words, but any word-wrapped text is
// affected) look glued into a single blob. Floor it to a legible fraction
// of the font's own height instead of touching letter spacing/kerning.
uint8_t withMinimumSpaceAdvance(uint8_t xAdvance, uint8_t codepoint, uint8_t glyphHeight) {
  if (codepoint != ' ') {
    return xAdvance;
  }
  const uint8_t minAdvance =
      static_cast<uint8_t>(std::max(1, (static_cast<int>(glyphHeight) * 7 + 10) / 20));  // ~0.35x
  return std::max(xAdvance, minAdvance);
}

ReaderGlyph glyphFor(char c, DisplayManager::ReaderTypeface typeface) {
  const uint8_t value = LatinText::byteValue(c);
  uint8_t baseValue = 0;
  const uint8_t lookupValue = invertedPunctuationBaseByte(value, baseValue) ? baseValue : value;

  switch (typeface) {
    case DisplayManager::ReaderTypeface::OpenDyslexic: {
      const uint8_t glyphValue =
          (lookupValue >= kEmbeddedOpenDyslexicFirstChar &&
           lookupValue <= kEmbeddedOpenDyslexicLastChar)
              ? lookupValue
              : LatinText::fallbackAsciiByte(lookupValue);
      const EmbeddedOpenDyslexicGlyph &glyph =
          kEmbeddedOpenDyslexicGlyphs[glyphValue - kEmbeddedOpenDyslexicFirstChar];
      return {kEmbeddedOpenDyslexicBitmaps + glyph.bitmapOffset, glyph.xOffset, glyph.width,
              glyph.xAdvance, kEmbeddedOpenDyslexicHeight};
    }
    case DisplayManager::ReaderTypeface::AtkinsonHyperlegible: {
      const uint8_t glyphValue =
          (lookupValue >= kEmbeddedAtkinsonFirstChar && lookupValue <= kEmbeddedAtkinsonLastChar)
              ? lookupValue
              : LatinText::fallbackAsciiByte(lookupValue);
      const EmbeddedAtkinsonGlyph &glyph =
          kEmbeddedAtkinsonGlyphs[glyphValue - kEmbeddedAtkinsonFirstChar];
      return {kEmbeddedAtkinsonBitmaps + glyph.bitmapOffset, glyph.xOffset, glyph.width,
              glyph.xAdvance, kEmbeddedAtkinsonHeight};
    }
    case DisplayManager::ReaderTypeface::Standard:
      return serifGlyphForByte(lookupValue);
    default: {
      if (!isExtraTypeface(typeface)) {
        return serifGlyphForByte(lookupValue);
      }
      const EmbeddedFontVariant &variant = extraFontVariant(typeface);
      const uint8_t glyphValue = (lookupValue >= variant.firstChar && lookupValue <= variant.lastChar)
                                      ? lookupValue
                                      : LatinText::fallbackAsciiByte(lookupValue);
      const EmbeddedFontGlyph &glyph = variant.glyphs[glyphValue - variant.firstChar];
      const uint8_t xAdvance =
          withMinimumSpaceAdvance(glyph.xAdvance, lookupValue, variant.height);
      return {variant.bitmaps + glyph.bitmapOffset, glyph.xOffset, glyph.width, xAdvance,
              variant.height};
    }
  }
}

